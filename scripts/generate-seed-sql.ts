// Generates supabase/seed/*.sql from the TypeScript seed sets, so demo mode
// and the hosted database start from exactly the same content.
// Usage: bun run seed:sql
import { mkdir, writeFile } from "node:fs/promises";
import { SEED_SETS } from "../src/data/seed";

const ORDER = [
  "wilayas", "communes", "service_types", "events", "categories", "category_service_types",
  "content_items", "providers", "provider_services", "provider_media", "offers",
  "price_items", "price_records", "translations",
];

function lit(v: unknown): string {
  if (v === null || v === undefined) return "null";
  if (typeof v === "number") return String(v);
  if (typeof v === "boolean") return v ? "true" : "false";
  return `'${String(v).replace(/'/g, "''")}'`;
}

const HEADERS: Record<string, string> = {
  reference: "REFERENCE DATA — real wilayas, communes and provider service types.",
  starter: "STARTER CONTENT — editable events, categories, subcategories and guidance (not demo).",
  demo: "DEMO DATA — FICTIONAL providers, portfolio images, offers and prices (is_demo = true).\n-- Remove at any time from Admin → Demo content, or: select public.delete_demo_content();",
};

await mkdir("supabase/seed", { recursive: true });
let n = 1;
for (const [name, builder] of Object.entries(SEED_SETS)) {
  const lines = [`-- 3ARSSI seed ${String(n).padStart(2, "0")} · ${HEADERS[name]}`,
    "-- Generated by scripts/generate-seed-sql.ts — edit the TypeScript source, not this file.",
    "-- Idempotent: safe to run more than once.", "begin;", ""];
  for (const table of ORDER) {
    const rows = builder.tables[table];
    if (!rows?.length) continue;
    const cols = Object.keys(rows[0]);
    lines.push(`-- ${table} (${rows.length})`);
    for (let i = 0; i < rows.length; i += 200) {
      const chunk = rows.slice(i, i + 200);
      lines.push(`insert into public.${table} (${cols.join(", ")}) values`);
      lines.push(chunk.map((r) => `  (${cols.map((c) => lit(r[c])).join(", ")})`).join(",\n"));
      lines.push("on conflict do nothing;");
    }
    lines.push("");
  }
  lines.push("commit;", "");
  const file = `supabase/seed/${String(n).padStart(2, "0")}_${name}.sql`;
  await writeFile(file, lines.join("\n"));
  console.log("wrote", file);
  n++;
}
